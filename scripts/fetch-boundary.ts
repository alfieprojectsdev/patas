/**
 * Regenerate src/lib/service-area.ts, Patas's service area, from OSM via
 * Nominatim lookup; run rarely. Currently Metro Manila (National Capital
 * Region, relation 147488).
 *
 * Writes two rings. AREA_RING is the legal boundary and decides what's in
 * scope. It takes in stretches of Manila Bay and Laguna de Bay, so
 * AREA_LAND_RING clips it to the OSM coastline (one Overpass request) and the
 * lake's shore (relation 79348, one more Nominatim request), with
 * src/lib/coast.ts. That one is for drawing the outline and for precompute cells.
 *
 *   node --experimental-strip-types scripts/fetch-boundary.ts
 *
 * Data © OpenStreetMap contributors, ODbL.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { overpassFetchInParts } from "./overpass.ts";
import { clipToLand, shoreOf, stitch, type CoastWay, type Pt } from "../src/lib/coast.ts";

const REL = 147488;
const NAME = "Metro Manila";
const LAKE = 79348; // Laguna de Bay

/** A relation's polygon from Nominatim: its outer ring, rounded, and its name. */
async function relationRing(rel: number): Promise<{ name: string; outer: Pt[]; rings: number }> {
  const url = `https://nominatim.openstreetmap.org/lookup?osm_ids=R${rel}&format=jsonv2&polygon_geojson=1`;
  const res = await fetch(url, { headers: { "User-Agent": "patas/0.1 (boundary fetch)" }, signal: AbortSignal.timeout(60_000) });
  if (!res.ok) throw new Error(`Nominatim ${res.status}`);
  const [hit] = (await res.json()) as Array<{ display_name: string; geojson: { type: string; coordinates: number[][][] } }>;
  if (!hit || hit.geojson.type !== "Polygon") throw new Error(`relation ${rel}: expected a Polygon, got ${hit?.geojson.type}`);
  const outer = hit.geojson.coordinates[0].map(([lng, lat]) => [+lng.toFixed(6), +lat.toFixed(6)] as Pt);
  return { name: hit.display_name, outer, rings: hit.geojson.coordinates.length };
}

const area = await relationRing(REL);
if (area.rings !== 1) throw new Error(`expected a single-ring boundary, got ${area.rings} rings`);
const ring = area.outer;
await new Promise((r) => setTimeout(r, 1100)); // Nominatim: one request a second
// The lake's islands (Talim and others) are its inner rings; only the outer shore matters here.
const lake = shoreOf((await relationRing(LAKE)).outer);

const lngs = ring.map((p) => p[0]);
const lats = ring.map((p) => p[1]);
const pad = 0.05;
// Public mirrors often refuse the first try (2026-10-18: 502, 500, 504, 500), so retry a minute apart.
// COAST_CACHE=<file> keeps the coastline response between runs while tuning the clip.
const cache = process.env.COAST_CACHE;
const coast = cache && existsSync(cache) ? JSON.parse(readFileSync(cache, "utf8")) : await overpassFetchInParts(
  (bbox) => `[out:json][timeout:120];way["natural"="coastline"](${bbox});out geom;`,
  { south: Math.min(...lats) - pad, west: Math.min(...lngs) - pad, north: Math.max(...lats) + pad, east: Math.max(...lngs) + pad },
  "coastline",
  { rows: 1, cols: 1, rounds: 8 },
);
if (cache && !existsSync(cache)) writeFileSync(cache, JSON.stringify(coast));
// Mainland coast only. Closed chains are islands (one off Pasay, at 120.93-120.94 E, is probably
// reclamation); following their shore would leave fragments of outline out in the bay.
const chains = stitch(coast.elements as unknown as CoastWay[]).filter((c) => c[0][0] !== c.at(-1)![0] || c[0][1] !== c.at(-1)![1]);
const land = clipToLand(ring, [...chains, lake]);

writeFileSync(
  "src/lib/service-area.ts",
  `// GENERATED by scripts/fetch-boundary.ts on ${new Date().toISOString().slice(0, 10)} — do not edit.
// ${area.name} (OSM relation ${REL}). Data © OpenStreetMap contributors, ODbL.
// Single outer ring, GeoJSON order [lng, lat], closed (first == last).
export const AREA_NAME = ${JSON.stringify(NAME)};
export const AREA_OSM_RELATION = ${REL};
export const AREA_RING: [number, number][] = ${JSON.stringify(ring)};
`,
);
// A separate file so the map's browser bundle doesn't carry the legal ring too.
writeFileSync(
  "src/lib/service-area-land.ts",
  `// GENERATED by scripts/fetch-boundary.ts on ${new Date().toISOString().slice(0, 10)} — do not edit.
// ${area.name} (OSM relation ${REL}). Data © OpenStreetMap contributors, ODbL.
// Map outline and precompute cells only; scope uses AREA_RING in service-area.ts.
// The same ring clipped to the OSM coastline (via ${coast.host}) and Laguna de Bay's shore (relation ${LAKE}): ${land.seaVertices} vertices in water replaced.
export const AREA_LAND_RING: [number, number][] = ${JSON.stringify(land.ring)};
`,
);
console.log(
  `wrote src/lib/service-area.ts and service-area-land.ts: ${ring.length} vertices, ${land.ring.length} on land (${land.seaVertices} in water; ${chains.length} coastline chains + the lake); westmost ${Math.min(...lngs)} -> ${Math.min(...land.ring.map((p) => p[0]))}`,
);
